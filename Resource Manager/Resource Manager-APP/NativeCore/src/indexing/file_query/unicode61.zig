pub fn isTokenScalar(value: u21) bool {
    var low: usize = 0;
    var high: usize = token_ranges.len;
    while (low < high) {
        const middle = low + (high - low) / 2;
        const range = token_ranges[middle];
        if (value < range.first) {
            high = middle;
        } else if (value > range.last) {
            low = middle + 1;
        } else {
            return true;
        }
    }
    return false;
}
