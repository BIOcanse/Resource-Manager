#Requires -Version 7
[CmdletBinding()]
param(
    [string]$Output = (Join-Path $PSScriptRoot '../../../src/Core/NativeCore/src/interaction/http/http_json_allowed_bmp.zig'),
    [switch]$Check
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

# Protocol data from the pre-Z1 ASP.NET Core 10 HTTP JSON encoder, not a new
# application preference. Regenerate and compare with the old HTTP oracle when
# changing the protocol's encoding contract or its runtime's Unicode data.
if ([Environment]::Version.Major -ne 10) { throw 'Generate the HTTP JSON contract with the .NET 10 runtime.' }
$encoder = [System.Text.Encodings.Web.JavaScriptEncoder]::UnsafeRelaxedJsonEscaping
$bits = [byte[]]::new(([int][char]::MaxValue + 1) / 8)
for ($value = 0; $value -le [int][char]::MaxValue; $value++) {
    # WillEncode accepts Unicode scalars only; UTF-16 surrogate code units are
    # encoded separately by the native codec, including replacement on invalid input.
    if ($value -ge 0xD800 -and $value -le 0xDFFF) { continue }
    if (-not $encoder.WillEncode($value)) {
        $slot = $value -shr 3
        $bits[$slot] = $bits[$slot] -bor (1 -shl ($value -band 7))
    }
}
$lines = [Collections.Generic.List[string]]::new()
$lines.Add('// Generated by build/scripts/build/Generate-HttpJsonEscaping.ps1; do not edit.')
$lines.Add('// ASP.NET Core 10 original HTTP JSON contract: UnsafeRelaxedJsonEscaping BMP bitmap.')
$lines.Add('pub fn allowed(value: u16) bool {')
$lines.Add('    return bits[value >> 6] & (@as(u64, 1) << @as(u6, @truncate(value))) != 0;')
$lines.Add('}')
$lines.Add('')
$lines.Add('const bits = [_]u64{')
for ($offset = 0; $offset -lt $bits.Length; $offset += 8) {
    $word = [BitConverter]::ToUInt64($bits, $offset)
    $lines.Add('    0x' + $word.ToString('X16', [Globalization.CultureInfo]::InvariantCulture) + ',')
}
$lines.Add('};')
$content = [string]::Join("`n", $lines) + "`n"
$encoding = [Text.UTF8Encoding]::new($false)
if ($Check) {
    if (-not [IO.File]::Exists($Output) -or [IO.File]::ReadAllText($Output, $encoding) -cne $content) {
        throw 'HTTP JSON escaping contract is stale; regenerate with .NET 10 and review the HTTP equivalence tests.'
    }
}
else {
    [void][IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName([IO.Path]::GetFullPath($Output)))
    [IO.File]::WriteAllText($Output, $content, $encoding)
}