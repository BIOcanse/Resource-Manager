//! A projection of the existing preference declarations, with no new defaults.
const std = @import("std");
const fields = .{
    .{ "memory_protection_notify", "MemoryProtectionNotify" },
    .{ "memory_protection_system", "MemoryProtectionSystem" },
    .{ "update_notify", "UpdateNotify" },
    .{ "update_system", "UpdateSystem" },
    .{ "access_request_notify", "AccessRequestNotify" },
    .{ "access_request_system", "AccessRequestSystem" },
    .{ "crash_report_notify", "CrashReportNotify" },
    .{ "crash_report_system", "CrashReportSystem" },
};
pub fn emit(allocator: std.mem.Allocator, bytes: []const u8, w: *std.Io.Writer) !void {
    const parsed = try std.json.parseFromSlice(std.json.Value, allocator, bytes, .{ .duplicate_field_behavior = .@"error" });
    defer parsed.deinit();
    if (parsed.value != .object) return error.InvalidPreferences;
    const points = parsed.value.object.get("points") orelse return error.MissingPoints;
    if (points != .array) return error.InvalidPoints;
    var selected: [fields.len]bool = undefined;
    var seen: [fields.len]bool = @splat(false);
    for (points.array.items) |point| {
        if (point != .object) return error.InvalidPoint;
        if (point.object.get("group")) |group| {
            if (group == .integer and group.integer == 2) return error.OverlayPointsBelongToBackend;
        }
        const symbol = point.object.get("symbol") orelse return error.MissingSymbol;
        if (symbol != .string) return error.InvalidSymbol;
        inline for (fields, 0..) |field, i| {
            if (std.mem.eql(u8, symbol.string, field[1])) {
                if (seen[i]) return error.DuplicateNotificationPoint;
                seen[i] = true;
                const kind = point.object.get("type") orelse return error.MissingType;
                const options = point.object.get("options") orelse return error.MissingOptions;
                if (kind != .string or !std.mem.eql(u8, kind.string, "choice") or options != .array or options.array.items.len != 2) return error.ExpectedOnOffChoice;
                for (options.array.items, [_][]const u8{ "on", "off" }) |option, expected| {
                    if (option != .string or !std.mem.eql(u8, option.string, expected)) return error.ExpectedOnOffChoice;
                }
                const value = point.object.get("value") orelse return error.MissingValue;
                if (value != .string or (!std.mem.eql(u8, value.string, "on") and !std.mem.eql(u8, value.string, "off"))) return error.InvalidChoice;
                selected[i] = std.mem.eql(u8, value.string, "on");
            }
        }
    }
    for (seen) |found| if (!found) return error.MissingNotificationPoint;
    try w.writeAll("// Generated by Generate-DesktopFrontendDefaults.ps1 from src/UI/Frontend/preferences.points.json.\n// Declared frontend point values for what the preference cache does not hold.\n");
    inline for (fields, 0..) |field, i| try w.print("pub const {s}: bool = {s};\n", .{ field[0], if (selected[i]) @as([]const u8, "true") else "false" });
}
