[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$Registry,
    [Parameter(Mandatory)][ValidateSet('backend', 'ui')][string]$Process,
    [Parameter(Mandatory)][string]$Namespace,
    [Parameter(Mandatory)][string]$Output
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
Import-Module (Join-Path $PSScriptRoot 'StateItemRegistry.psm1') -Force

$bytes = [IO.File]::ReadAllBytes([IO.Path]::GetFullPath($Registry))
$table = Read-StateRegistry -Bytes $bytes
$version = Get-StateRegistryVersion $bytes
$entries = @($table.entries | Where-Object process -CEQ $Process)
$lines = [Collections.Generic.List[string]]::new()
$lines.Add('// <auto-generated> from src/Shared/StateItems/state-items.json by scripts/build/Generate-StateItems.ps1. Do not edit.')
$lines.Add('#nullable enable')
$lines.Add('using ResourceManager.Shared.BusinessBlocks.State;')
$lines.Add("namespace $Namespace;")
$lines.Add('')
$lines.Add('internal static class StateRegistry')
$lines.Add('{')
$lines.Add('    /// <summary>Git object id of the registry file this build was generated from.</summary>')
$lines.Add("    public const string Version = `"$version`";")
$lines.Add('    public static System.Collections.Generic.IReadOnlyList<int> Blocks { get; } = System.Array.AsReadOnly(new int[]')
$lines.Add('    {')
foreach ($entry in $entries | Where-Object kind -CEQ 'block') { $lines.Add("        $($entry.uid),") }
$lines.Add('    });')
$lines.Add('    public static System.Collections.Generic.IReadOnlyList<StateItemDeclaration> Items { get; } = System.Array.AsReadOnly(new StateItemDeclaration[]')
$lines.Add('    {')
foreach ($entry in $entries | Where-Object kind -CEQ 'item') {
    $storage = if ($entry.storage -ceq 'own') { 'Own' } else { 'Reference' }
    $trigger = if ($entry.trigger -ceq 'event') { 'Event' } else { 'Poll' }
    $perBlock = if ($entry.perBlock) { 'true' } else { 'false' }
    $pollInterval = if ($entry.ContainsKey('pollInterval')) { ConvertTo-Json -InputObject $entry.pollInterval -Compress -EscapeHandling EscapeNonAscii } else { 'null' }
    if ($entry.owner.ContainsKey('block')) {
        $owner = "new(StateItemOwnerKind.Block, $($entry.owner.block))"
        $lines.Add("        new($($entry.uid), StateItemStorage.$storage, typeof($($entry.type)), $owner, $perBlock, StateItemTrigger.$trigger, $pollInterval),")
    } else {
        # Component identity is the capability claimed for this item, not its diagnostic label.
        # Labels may contain block/item names, so they exist only in development builds.
        $component = ConvertTo-Json -InputObject $entry.owner.component -Compress -EscapeHandling EscapeNonAscii
        $lines.Add("        new($($entry.uid), StateItemStorage.$storage, typeof($($entry.type)), new(StateItemOwnerKind.Component, ComponentLabel:")
        $lines.Add('#if RM_STATE_NAMES')
        $lines.Add("            $component")
        $lines.Add('#else')
        $lines.Add('            null')
        $lines.Add('#endif')
        $lines.Add("        ), $perBlock, StateItemTrigger.$trigger, $pollInterval),")
    }
}
$lines.Add('    });')
$lines.Add('}')
foreach ($kind in @('block', 'item')) {
    $class = if ($kind -eq 'block') { 'BlockUids' } else { 'StateItemUids' }
    $lines.Add('')
    $lines.Add("internal static class $class")
    $lines.Add('{')
    foreach ($entry in $entries | Where-Object kind -CEQ $kind) { $lines.Add("    public const int $($entry.name) = $($entry.uid);") }
    $lines.Add('}')
}
$lines.Add('')
$lines.Add('#if RM_STATE_NAMES')
$lines.Add('internal static class StateNames')
$lines.Add('{')
foreach ($field in @('name', 'comment')) {
    $method = if ($field -eq 'name') { 'Name' } else { 'Comment' }
    $lines.Add("    public static string? $method(int uid) => uid switch")
    $lines.Add('    {')
    foreach ($entry in $entries) {
        # JSON string escaping is also valid for C# regular string literals.
        $literal = ConvertTo-Json -InputObject $entry[$field] -Compress -EscapeHandling EscapeNonAscii
        $lines.Add("        $($entry.uid) => $literal,")
    }
    $lines.Add('        _ => null')
    $lines.Add('    };')
}
$lines.Add('}')
$lines.Add('#endif')
$content = [string]::Join("`n", $lines) + "`n"
$path = [IO.Path]::GetFullPath($Output)
if (-not [IO.File]::Exists($path) -or [IO.File]::ReadAllText($path) -cne $content) {
    [IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($path)) | Out-Null
    [IO.File]::WriteAllText($path, $content, [Text.UTF8Encoding]::new($false))
}
