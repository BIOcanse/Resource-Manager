[CmdletBinding()]
param([string]$Output = (Join-Path $PSScriptRoot '../../src/UI/Desktop/src/generated/frontend_defaults.zig'))
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
# The resident reads the frontend preference cache. A value the cache does not
# hold has the frontend point's declared value, as NativeUi's FrontendPoints has:
# the notification switches (group 1).
$declaration = Get-Content -LiteralPath (Join-Path $PSScriptRoot '../../src/UI/Frontend/preferences.points.json') -Raw | ConvertFrom-Json
$points = @($declaration.points)

function Get-Point([string]$Symbol) {
    $point = @($points | Where-Object { $_.symbol -ceq $Symbol })
    if ($point.Count -ne 1) { throw "Frontend point $Symbol is declared $($point.Count) times." }
    $point[0]
}
$lines = [Collections.Generic.List[string]]::new()
$lines.Add('// Generated by Generate-DesktopFrontendDefaults.ps1 from src/UI/Frontend/preferences.points.json.')
$lines.Add('// Declared frontend point values for what the preference cache does not hold.')

# Notification switches: Zig field = frontend point symbol; each is an on/off choice.
$switches = [ordered]@{
    memory_protection_notify = 'MemoryProtectionNotify'
    memory_protection_system = 'MemoryProtectionSystem'
    update_notify = 'UpdateNotify'
    update_system = 'UpdateSystem'
    access_request_notify = 'AccessRequestNotify'
    access_request_system = 'AccessRequestSystem'
    crash_report_notify = 'CrashReportNotify'
    crash_report_system = 'CrashReportSystem'
}
foreach ($name in $switches.Keys) {
    $point = Get-Point $switches[$name]
    if ($point.type -cne 'choice' -or (@($point.options) -join ',') -cne 'on,off') { throw "Frontend point $($point.symbol) is not an on/off choice." }
    $lines.Add("pub const ${name}: bool = $(if ($point.value -ceq 'on') { 'true' } else { 'false' });")
}

# The overlay is not a frontend point any more: its settings and their defaults are the backend settings
# section performanceOverlay (freedom point monitoring/performance_overlay), received through the settings
# subscription. A frontend point in the former overlay group would be a second owner.
$overlayPoints = @($points | Where-Object { $_.group -eq 2 } | ForEach-Object { $_.symbol })
if ($overlayPoints.Count -gt 0) { throw "Overlay frontend points are declared again: $($overlayPoints -join ', '); overlay settings belong to the backend." }
[IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName([IO.Path]::GetFullPath($Output))) | Out-Null
[IO.File]::WriteAllText([IO.Path]::GetFullPath($Output), ($lines -join "`n") + "`n", [Text.UTF8Encoding]::new($false))
