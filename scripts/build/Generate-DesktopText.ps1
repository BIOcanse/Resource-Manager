[CmdletBinding()]
param([string]$Output = (Join-Path $PSScriptRoot '../../src/UI/Desktop/src/text/generated/tray.zig'))
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
# Layout step 5 replaces NativeText with shared frontend resources. Until then,
# derive resident copy from the current native catalog, without a second owner.
$source = Join-Path $PSScriptRoot '../../src/UI/Core/Localization/Texts'
$languageContract = [IO.File]::ReadAllText((Join-Path $PSScriptRoot '../../src/Shared/Localization/AppLanguage.cs'))
$fallback = [regex]::Match($languageContract, 'const string Fallback = "([^"]+)"').Groups[1].Value
$supportedBlock = [regex]::Match($languageContract, 'SupportedIds\s*=\s*\[(.*?)\];', [Text.RegularExpressions.RegexOptions]::Singleline).Groups[1].Value
$supported = @([regex]::Matches($supportedBlock, '"([^"]+)"') | ForEach-Object { $_.Groups[1].Value })
if (-not $fallback -or $supported.Count -eq 0 -or $supported -cnotcontains $fallback) { throw 'Shared language contract could not be read.' }
# Zig field = native catalog key. Tray menu, balloons of the resident's blocks.
$fields = [ordered]@{
    open = 'TrayOpen'
    exit = 'TrayExit'
    memory_protection_title = 'MemoryProtectionTitle'
    memory_protection_process = 'MemoryProtectionProcessMessageFormat'
    memory_protection_tree = 'MemoryProtectionTreeMessageFormat'
    update_available_title = 'UpdateAvailableTitle'
    update_available = 'UpdateAvailableMessageFormat'
    access_request_title = 'AccessRequestTitle'
    access_request = 'AccessRequestMessageFormat'
    crash_report_title = 'CrashReportTitle'
    crash_report = 'CrashReportMessage'
    force_terminate_title = 'ForceTerminateHotkeyBalloonTitle'
    no_foreground_process = 'NoForegroundProcessToTerminate'
    backend_unavailable_no_terminate = 'BackendUnavailableNoTerminate'
    force_terminate_failed = 'ForceTerminateFailed'
    terminate_result = 'TerminateResultFormat'
    no_process_to_terminate = 'NoProcessToTerminate'
    force_terminate_disabled = 'ForceTerminateHotkeyDisabled'
    force_terminate_enable_failed = 'ForceTerminateHotkeyEnableFailed'
    task_manager_title = 'TaskManagerHotkeyReplacement'
    task_manager_enable_failed = 'TaskManagerHotkeyEnableFailed'
    overlay_title = 'PerformanceOverlayTitle'
    overlay_enabled_format = 'PerformanceOverlayEnabledFormat'
    overlay_disabled_format = 'PerformanceOverlayDisabledFormat'
    overlay_no_foreground = 'PerformanceOverlayNoForegroundSoftware'
    overlay_backend_unavailable = 'PerformanceOverlayBackendUnavailable'
    overlay_toggle_failed = 'PerformanceOverlayToggleFailedFormat'
    overlay_hotkey_enable_failed = 'PerformanceOverlayHotkeyEnableFailed'
    overlay_menu_format = 'PerformanceOverlayMenuFormat'
    overlay_menu_no_software = 'PerformanceOverlayMenuNoSoftware'
    overlay_menu_backend_unavailable = 'PerformanceOverlayMenuBackendUnavailable'
    overlay_menu_read_failed = 'PerformanceOverlayMenuReadFailed'
}
function ConvertTo-ZigLiteral([string]$literal, [string]$key, [string]$file) {
    # C# regular literals and Zig literals share \" \\ \n \t; only \uXXXX differs.
    if ($literal -match '\\[^"\\ntu]') { throw "Unsupported escape in $key ($file)" }
    if ($literal -match '\\u[dD][89a-fA-F]') { throw "Surrogate escape in $key ($file)" }
    return [regex]::Replace($literal, '\\u([0-9A-Fa-f]{4})', { param($m) '\u{' + $m.Groups[1].Value + '}' })
}
$lines = [Collections.Generic.List[string]]::new()
$lines.Add('// Generated by Generate-DesktopText.ps1 from the native catalog.')
$lines.Add("pub const fallback_language = `"$fallback`";")
$lines.Add('pub const Text = struct {')
$lines.Add('    language: []const u8,')
foreach ($name in $fields.Keys) { $lines.Add("    ${name}: []const u8,") }
$lines.Add('};')
$lines.Add('pub const all = [_]Text{')
foreach ($language in $supported) {
    $file = Get-Item -LiteralPath (Join-Path $source ($language.Replace('-','') + '.cs'))
    $raw = [IO.File]::ReadAllText($file.FullName)
    $lines.Add('    .{')
    $lines.Add("        .language = `"$language`",")
    foreach ($name in $fields.Keys) {
        $key = $fields[$name]
        $match = [regex]::Match($raw, "\b$key = (`"(?:[^`"\\]|\\.)*`")")
        if (-not $match.Success -or $match.Groups[1].Value -eq '""') { throw "Missing $key in $($file.Name)" }
        $lines.Add("        .$name = $(ConvertTo-ZigLiteral $match.Groups[1].Value $key $file.Name),")
    }
    $lines.Add('    },')
}
$lines.Add('};')
[IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName([IO.Path]::GetFullPath($Output))) | Out-Null
[IO.File]::WriteAllText([IO.Path]::GetFullPath($Output), ($lines -join "`n") + "`n", [Text.UTF8Encoding]::new($false))
