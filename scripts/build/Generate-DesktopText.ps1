[CmdletBinding()]
param([string]$Output = (Join-Path $PSScriptRoot '../../src/UI/Desktop/src/text/generated/tray.zig'))
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
# Layout step 5 replaces NativeText with shared frontend resources. Until then,
# derive resident menu copy from the current native catalog, without a second owner.
$source = Join-Path $PSScriptRoot '../../src/UI/Core/Localization/Texts'
$languageContract = [IO.File]::ReadAllText((Join-Path $PSScriptRoot '../../src/Shared/Localization/AppLanguage.cs'))
$fallback = [regex]::Match($languageContract, 'const string Fallback = "([^"]+)"').Groups[1].Value
$supportedBlock = [regex]::Match($languageContract, 'SupportedIds\s*=\s*\[(.*?)\];', [Text.RegularExpressions.RegexOptions]::Singleline).Groups[1].Value
$supported = @([regex]::Matches($supportedBlock, '"([^"]+)"') | ForEach-Object { $_.Groups[1].Value })
if (-not $fallback -or $supported.Count -eq 0 -or $supported -cnotcontains $fallback) { throw 'Shared language contract could not be read.' }
$lines = [Collections.Generic.List[string]]::new()
$lines.Add('// Generated by Generate-DesktopText.ps1 from the native catalog.')
$lines.Add("pub const fallback_language = `"$fallback`";")
$lines.Add('pub const Text = struct { language: []const u8, open: []const u8, exit: []const u8 };')
$lines.Add('pub const all = [_]Text{')
foreach ($language in $supported) {
    $file = Get-Item -LiteralPath (Join-Path $source ($language.Replace('-','') + '.cs'))
    $raw = [IO.File]::ReadAllText($file.FullName)
    $open = [regex]::Match($raw, 'TrayOpen = ("(?:[^"\\]|\\.)*")').Groups[1].Value
    $exit = [regex]::Match($raw, 'TrayExit = ("(?:[^"\\]|\\.)*")').Groups[1].Value
    if (-not $open -or -not $exit) { throw "Missing tray copy in $($file.Name)" }
    $lines.Add("    .{ .language = `"$language`", .open = $open, .exit = $exit },")
}
$lines.Add('};')
[IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName([IO.Path]::GetFullPath($Output))) | Out-Null
[IO.File]::WriteAllText([IO.Path]::GetFullPath($Output), ($lines -join "`n") + "`n", [Text.UTF8Encoding]::new($false))
