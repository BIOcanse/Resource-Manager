import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { metricCatalogDecoder, metricSnapshotDecoder } from "../src/data/monitor/monitorSourceDecoders.ts";
import { metricSnapshotObservedAt } from "../src/data/monitor/metricSnapshotValue.ts";
import { metricCardReading, metricDisplayValue } from "../src/presentation/metricLabels.ts";
import { componentDisplayName, userFacingMetricGroup, userFacingMetricUnavailableReason } from "../src/presentation/userFacingText.ts";
import { applyByteUnitMode } from "../src/presentation/byteUnits.ts";
import { applyLanguage, uiText } from "../src/text.ts";
import { languageOptions } from "../src/i18n/settingsLanguages.ts";
import { loadAppCopy } from "../src/i18n/copy/appCopyLoader.ts";
import { appendPerformancePoint } from "../src/features/resourceTable/resourcePerformanceHistory.ts";
import { metricOfferedInPicker } from "../src/presentation/metricPresentation.ts";
import { formatLegacyMetricNumber } from "../src/presentation/legacyMetricNumber.ts";

// Fixed goldens come from .NET Double.ToString(customFormat, InvariantCulture),
// generated by scripts/generateMetricLegacyNumberGoldens.ps1, never by this helper.
const formatGoldens = JSON.parse(readFileSync(new URL("./fixtures/metricLegacyNumberGoldens.json", import.meta.url), "utf8")) as {
  scales: readonly (0 | 1 | 2 | 3)[];
  cases: readonly { input: string; expected: readonly string[] }[];
};
const aliasFormats = [
  { id: "cpu.frequency", unit: "MHz" },
  { id: "cpu.temperature", unit: "°C" },
  { id: "disk.total.queueLength", unit: "" },
  { id: "cpu.coreVoltage", unit: "V" }
];
for (const fixture of formatGoldens.cases) {
  for (const [index, scale] of formatGoldens.scales.entries()) {
    assert.equal(formatLegacyMetricNumber(Number(fixture.input), scale), fixture.expected[index], `${fixture.input} scale ${scale}`);
  }
}

// Recorded primitive-unit readings and their established presentation. No running backend is needed.
const readings = [
  ["cpu.usage", "%", 25, "25%", "cpu"],
  ["cpu.frequency", "MHz", 4212.4, "4212 MHz", "cpu"],
  ["cpu.temperature", "°C", 65.25, "65.3 °C", "cpu"],
  ["cpu.packagePower", "W", 35.25, "35.3 W", "cpu"],
  ["cpu.coreVoltage", "V", 1.2344, "1.234 V", "cpu"],
  ["cpu.packageCurrent", "A", 24.25, "24.3 A", "cpu"],
  ["cpu.fanRpm", "RPM", 3210, "3210 RPM", "fan"],
  ["cpu.fanPercent", "%", 45, "45%", "fan"],
  ["memory.usage", "B", 8 * 1024 ** 3, "8.00 GiB", "memory"],
  ["memory.percent", "%", 25, "25%", "memory"],
  ["memory.temperature", "°C", 45, "45 °C", "memory"],
  ["virtualMemory.usage", "B", 16 * 1024 ** 3, "16.0 GiB", "virtual-memory"],
  ["virtualMemory.percent", "%", 75, "75%", "virtual-memory"],
  ["gpu.1.usage", "%", 98.2, "98.2%", "gpu.1"],
  ["gpu.1.vram", "B", 4 * 1024 ** 3, "4.00 GiB", "gpu.1"],
  ["gpu.1.fanRpm", "RPM", 4200, "4200 RPM", "fan"],
  ["gpu.1.fanPercent", "%", 80, "80%", "fan"],
  ["disk.total.activePercent", "%", 50, "50%", "disk"],
  ["disk.total.queueLength", "", 1.2345, "1.23", "disk"],
  ["disk.total.readBytesPerSec", "B/s", 1_000_000, "1.00 MB/s", "disk"],
  ["disk.2.temperature", "°C", 40, "40 °C", "disk"],
  ["network.total.utilizationPercent", "%", 10, "10%", "network"],
  ["network.total.receiveBytesPerSec", "B/s", 1000, "1.00 kB/s", "network"],
  ["system.motherboardTemperature", "°C", 35, "35 °C", "motherboard"],
  ["fan.2.speed", "RPM", 2000, "2000 RPM", "fan"],
  ["target.fps", "FPS", 120, "120 FPS", "target-software"]
] as const;
const observedAt = "2026-10-24T10:00:00.000Z";
const rawItems = Object.fromEntries(readings.map(([id, unit, numericValue]) => [id, {
  id, unit, numericValue, status: 1, observedAt, sampleDurationMilliseconds: 1000,
  fieldCode: 0, fieldName: null, deviceIdentity: null, sourceId: "recorded", valueKind: "float64"
}]));
const rawSnapshot = { version: 5, capturedAt: observedAt, catalogRevision: "recorded-raw-v5", items: rawItems };
const snapshot = metricSnapshotDecoder.decode(rawSnapshot);
const catalog = metricCatalogDecoder.decode(readings.map(([id, unit]) => ({ id, unit, selectable: true })));

// The already shipped overlay manifest records the established nine-language alias names.
const recordedLabels = JSON.parse(readFileSync(new URL("../../Core/Overlay/metric-labels.json", import.meta.url), "utf8")) as Record<string, Record<string, string>>;
const allAliasDefinitions = Object.keys(recordedLabels).map(id => ({ id: id.replaceAll("{index}", "2"), unit: "%" }));
const aliasCatalog = metricCatalogDecoder.decode(allAliasDefinitions);
const unavailable = metricCatalogDecoder.decode([{
  id: "cpu.temperature", unit: "°C", selectable: false,
  requiredComponentId: "intel-msr-pawnio-provider", disabledReason: { domain: 3, code: 2, args: ["intel-msr-pawnio-provider"] }
}])[0];
const canonical = metricCatalogDecoder.decode([{
  id: "cpu_all_usage_percent@opaque-device", unit: "%", fieldCode: 1,
  fieldName: "cpu_all_usage_percent", deviceIdentity: "opaque-device", sourceId: "windows.cpu", valueKind: "float64", scopeKind: "cpu"
}])[0];
const languages = languageOptions.filter(option => option.id !== "system");
assert.equal(languages.length, 9);
applyByteUnitMode("native");
for (const language of languages) {
  await applyLanguage(language.id);
  const copy = await loadAppCopy(language.id as Parameters<typeof loadAppCopy>[0]);
  for (const [pattern, names] of Object.entries(recordedLabels)) {
    const id = pattern.replaceAll("{index}", "2");
    assert.equal(aliasCatalog.find(item => item.id === id)?.label, names[language.id].replaceAll("{index}", "2"), `${language.id}: ${id}`);
  }
  for (const [id, , , display, group] of readings) {
    const definition = catalog.find(item => item.id === id)!;
    const metric = snapshot.items[id];
    assert.equal(metricDisplayValue(metric), display, `${language.id}: ${id} display`);
    const reading = metricCardReading(definition, metric);
    assert.equal(reading.value + reading.gap + reading.unit, display);
    assert.equal(reading.missing, false);
    assert.equal(definition.group, group);
    assert.equal(metric.group, group);
    assert.equal(metric.label, definition.label);
    assert.equal(metricSnapshotObservedAt(snapshot, id), observedAt);
    assert.ok(userFacingMetricGroup(group));
  }
  assert.equal(userFacingMetricGroup("memory"), copy.status.metricGroup.memory);
  assert.equal(userFacingMetricGroup("fan"), copy.status.metricGroup.fan);
  assert.equal(canonical.label, copy.fieldLabel.cpu_all_usage_percent.label);
  assert.equal(metricOfferedInPicker(canonical), false, "canonical fields use the device-field picker rather than a duplicate raw address");
  assert.ok(catalog.every(metricOfferedInPicker));
  for (const id of ["cpu.igpuFrequency", "cpu.igpuVoltage", "cpu.igpuTemperature"]) {
    assert.equal(metricOfferedInPicker(aliasCatalog.find(item => item.id === id)!), false, "iGPU aliases stay on the GPU/device route");
  }
  assert.equal(unavailable.requiredComponentName, componentDisplayName("intel-msr-pawnio-provider"));
  assert.equal(userFacingMetricUnavailableReason(unavailable.requiredComponentName, unavailable.disabledReason), copy.backendMessage.metric.needsComponent(unavailable.requiredComponentName!));
  assert.equal(metricCardReading(unavailable, null).value, copy.dashboard.needsComponent);
  assert.equal(metricDisplayValue({ status: 1, booleanValue: false }), copy.shellBridge.no);
  for (const fixture of formatGoldens.cases) {
    for (const [index, alias] of aliasFormats.entries()) {
      const frame = metricSnapshotDecoder.decode({ ...rawSnapshot, items: {
        [alias.id]: { id: alias.id, unit: alias.unit, status: 1, numericValue: Number(fixture.input) }
      } });
      const expected = `${fixture.expected[index]} ${alias.unit}`.trimEnd();
      const actual = frame.items[alias.id];
      assert.equal(metricDisplayValue(actual), expected, `${language.id}: ${alias.id} ${fixture.input}`);
      const card = metricCardReading(null, actual);
      assert.equal(card.value + card.gap + card.unit, expected, `${language.id}: card ${alias.id} ${fixture.input}`);
    }
  }
}

const exact = "340282366920938463463374607431768211455";
const exactValue = metricSnapshotDecoder.decode({ ...rawSnapshot, items: {
  exact: { id: "exact", unit: "count", status: 1, numericValue: null, integerValue: exact },
  flags: { id: "flags", unit: "bitmask64", status: 1, numericValue: null, integerValue: "18446744073709551615", bytesValue: "AQID" }
} });
assert.equal(exactValue.items.exact.integerValue, exact);
assert.equal(metricDisplayValue(exactValue.items.exact).replaceAll(/[^0-9]/g, ""), exact);
assert.equal(metricDisplayValue(exactValue.items.flags), "0xFFFFFFFFFFFFFFFF");
assert.equal(exactValue.items.flags.bytesValue, "AQID");
for (const integerValue of [42, "1.5", "340282366920938463463374607431768211456", "-9223372036854775809"]) {
  assert.throws(() => metricSnapshotDecoder.decode({ ...rawSnapshot, items: { bad: { id: "bad", unit: "count", status: 1, numericValue: null, integerValue } } }), /integerValue/);
}
for (const status of [0, 2, 3, 4, 5, 6, 7]) {
  const unavailableFrame = metricSnapshotDecoder.decode({ ...rawSnapshot, items: { "cpu.usage": { ...rawItems["cpu.usage"], status } } });
  assert.equal(metricDisplayValue(unavailableFrame.items["cpu.usage"]), "--");
  assert.equal(metricSnapshotObservedAt(unavailableFrame, "cpu.usage"), null);
  assert.equal(appendPerformancePoint(unavailableFrame, [{ id: "cpu.usage", label: "CPU", color: "#000" }]).values["cpu.usage"], null);
}
assert.throws(() => metricSnapshotDecoder.decode({ ...rawSnapshot, version: 4 }), /version/);
assert.equal(metricCatalogDecoder.decode([{ id: "cpu.usage", unit: "%", label: "untrusted", group: "untrusted", preferredSlot: "untrusted" }])[0].group, "cpu");
assert.equal(metricDisplayValue(metricSnapshotDecoder.decode({ ...rawSnapshot, items: { "cpu.usage": { ...rawItems["cpu.usage"], displayValue: "untrusted" } } }).items["cpu.usage"]), "25%");
console.log(`Raw metric presentation passed: ${languages.length} languages, ${aliasCatalog.length} recorded aliases, ${readings.length} raw readings, ${formatGoldens.cases.length * formatGoldens.scales.length} .NET numeric format goldens.`);
