import assert from "node:assert/strict";
import type { Page } from "playwright-core";
import type { Telemetry } from "./mockFrontendServerTypes.ts";
import { mkdir } from "node:fs/promises";
import { join } from "node:path";
import { loadAppCopy } from "../../src/i18n/copy/appCopyLoader.ts";
import { ResourceManager } from "../../src/preferences/generated/frontendPoints.values.ts";
import { readFrontendPreferences, writeFrontendPreferences } from "./frontendPreferencesFixture.ts";
import { waitForCondition } from "./journeyWaits.ts";

export default async function resourceTableColumnsJourney(page: Page, baseUrl: string) {
  const shots = process.env.RM_BROWSER_ARTIFACT_DIR;
  if (!shots) throw new Error("Set RM_BROWSER_ARTIFACT_DIR inside the registered worker ledger");
  await mkdir(shots, { recursive: true });
  const app = await loadAppCopy("en-US"), view = app.resourceTableView;
  await page.request.post(`${baseUrl}/__test/scenario`, { data: { resourceTableVariant: "many", resourceTableRowCount: 12 } });
  await page.setViewportSize({ width: 1400, height: 900 });
  await page.goto(baseUrl, { waitUntil: "domcontentloaded" });
  await writeFrontendPreferences(page, value => { value.appearance.language = "en-US"; });
  await page.reload({ waitUntil: "domcontentloaded" });
  const panel = page.locator(".resource-table-panel");
  await panel.scrollIntoViewIfNeeded();
  await panel.locator(".resource-table-frame").waitFor();
  await panel.getByRole("button", { name: view.editLabel, exact: true }).click();
  const resizer = panel.getByRole("separator", { name: view.resizeColumn(app.resourceTable.columns.name), exact: true });
  const width = async () => Number(await resizer.getAttribute("aria-valuenow"));
  const original = await width();
  await resizer.scrollIntoViewIfNeeded();
  const box = await resizer.boundingBox();
  assert.ok(box);
  const x = box.x + box.width / 2, y = box.y + box.height / 2;
  await page.mouse.move(x, y); await page.mouse.down();
  await page.mouse.move(x + 60, y, { steps: 8 }); await page.mouse.up();
  await page.waitForFunction(([handle, before]) => Number(handle!.getAttribute("aria-valuenow")) > before,
    [await resizer.elementHandle(), original] as const);
  const dragged = await width();
  await resizer.focus(); await page.keyboard.press("ArrowRight");
  await page.waitForFunction(([handle, expected]) => Number(handle!.getAttribute("aria-valuenow")) === expected,
    [await resizer.elementHandle(), dragged + ResourceManager.FrontendPoints.TableColumnResizeKeyStep] as const);
  await page.keyboard.press("End");
  assert.equal(await width(), ResourceManager.FrontendPoints.DashboardLayoutLimits.maximumColumnWidth);
  await resizer.dblclick();
  assert.ok(await width() < ResourceManager.FrontendPoints.DashboardLayoutLimits.maximumColumnWidth);
  const fitted = await width();
  await panel.getByRole("button", { name: view.addColumn, exact: true }).click();
  const dialog = page.getByRole("dialog");
  const label = app.resourceTable.processFieldNames.process_all_handle_count_actual!;
  await dialog.getByRole("option").filter({ hasText: label }).click();
  await dialog.getByRole("button", { name: app.metricPicker.confirm, exact: true }).click();
  const header = panel.locator('.resource-table-head-cell').filter({ has: page.getByRole("button", { name: label, exact: true }) });
  await header.waitFor();
  await panel.locator(".resource-table-cell-text").filter({ hasText: /^42$/ }).first().waitFor();
  const requested = async () => {
    const telemetry = await (await page.request.get(`${baseUrl}/__test/requests`)).json() as Record<string, Telemetry | undefined>;
    return new URLSearchParams(telemetry["/api/resource-facts/subscribe"]?.queries?.at(-1) ?? "").getAll("items");
  };
  await waitForCondition(page, async () => (await requested()).includes("process_all_handle_count_actual"), { description: "Added field is subscribed" });
  await panel.screenshot({ path: join(shots, "table-resized-added.png") });
  await panel.getByRole("button", { name: view.saveLabel, exact: true }).click();
  await panel.getByRole("button", { name: view.editLabel, exact: true }).waitFor();
  const cached = (await readFrontendPreferences(page))!.dashboard!.resourceTableColumns;
  assert.equal(cached.find(column => column.id === "name")!.width, fitted);
  assert.ok(cached.some(column => column.id === "process_all_handle_count_actual"));
  await page.reload({ waitUntil: "domcontentloaded" });
  await panel.scrollIntoViewIfNeeded();
  await header.waitFor();
  await panel.getByRole("button", { name: view.editLabel, exact: true }).click();
  await panel.getByRole("button", { name: view.removeColumn(label), exact: true }).click();
  await header.waitFor({ state: "detached" });
  await waitForCondition(page, async () => !(await requested()).includes("process_all_handle_count_actual"), { description: "Removed field is unsubscribed" });
  await panel.getByRole("button", { name: view.cancelEditLabel, exact: true }).click();
  await header.waitFor();
  await panel.locator(".resource-table-cell-text").filter({ hasText: /^42$/ }).first().waitFor();
  await panel.screenshot({ path: join(shots, "table-reloaded-cancel-restored.png") });
  return { original, dragged, fitted, field: "process_all_handle_count_actual", screenshots: shots };
}
