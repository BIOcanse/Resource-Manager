import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { zhAppCopy } from "../src/i18n/copy/zh/index.ts";
import { enAppCopy } from "../src/i18n/copy/en/index.ts";
import { zhAppCopy as zhTwAppCopy } from "../src/i18n/copy/zh-TW/index.ts";
import ja from "../src/i18n/copy/locales/ja-JP.ts";
import ko from "../src/i18n/copy/locales/ko-KR.ts";
import fr from "../src/i18n/copy/locales/fr-FR.ts";
import de from "../src/i18n/copy/locales/de-DE.ts";
import es from "../src/i18n/copy/locales/es-ES.ts";
import ru from "../src/i18n/copy/locales/ru-RU.ts";
import type { AppCopy } from "../src/i18n/copy/index.ts";

const copies = {
  "zh-CN": zhAppCopy,
  "zh-TW": zhTwAppCopy,
  "en-US": enAppCopy,
  "ja-JP": ja,
  "ko-KR": ko,
  "fr-FR": fr,
  "de-DE": de,
  "es-ES": es,
  "ru-RU": ru
};
const indexSentinel = "7319";
const ids = (Object.keys(zhAppCopy.metricLabel) as (keyof AppCopy["metricLabel"])[]).sort();
const labels: Record<string, Record<string, string>> = {};
for (const id of ids) {
  labels[id] = {};
  for (const [language, copy] of Object.entries(copies)) {
    const entry = copy.metricLabel[id];
    if (entry === undefined) throw new Error(`${language}: missing metric ${id}`);
    // The overlay fills {index} with a number, so render with a number and swap it back: the copy's own spacing rule
    // (i18n/cjkSpacing.ts puts a space between a CJK character and a digit) then applies exactly as at run time.
    if (typeof entry === "function") {
      const rendered = entry(indexSentinel);
      if (rendered.split(indexSentinel).length !== 2) throw new Error(`${language}: ${id} must contain the index exactly once`);
      labels[id][language] = rendered.replace(indexSentinel, "{index}");
    } else {
      labels[id][language] = entry;
    }
  }
}
// Zig string literals: escape the quote, the backslash and control characters; other UTF-8 stays as written.
const zigString = (text: string) => `"${[...text].map((character) => {
  const code = character.codePointAt(0)!;
  if (character === "\"" || character === "\\") return `\\${character}`;
  return code < 0x20 || code === 0x7f ? `\\x${code.toString(16).padStart(2, "0")}` : character;
}).join("")}"`;
const languages = Object.keys(copies);
// 浮层项的其余文字（overlay/text.zig 按 overlayItemLabels.ts 的顺序查）：目标软件项的模板、进程字段名、取不到值的原因。
const nameSentinel = "NAME7319";
const softwareTemplate: Record<string, string> = {};
for (const [language, copy] of Object.entries(copies)) {
  const rendered = copy.performanceOverlay.itemSoftware(nameSentinel);
  if (rendered.split(nameSentinel).length !== 2) throw new Error(`${language}: itemSoftware must contain the name exactly once`);
  softwareTemplate[language] = rendered.replace(nameSentinel, "{name}");
}
const keyedTable = (pick: (copy: AppCopy) => Readonly<Record<string, string | undefined>>, what: string) => {
  const table: Record<string, Record<string, string>> = {};
  for (const key of Object.keys(pick(zhAppCopy)).sort()) {
    table[key] = {};
    for (const [language, copy] of Object.entries(copies)) {
      const text = pick(copy)[key];
      if (typeof text !== "string" || !text.trim()) throw new Error(`${language}: missing ${what} ${key}`);
      table[key][language] = text;
    }
  }
  return table;
};
const processFields = keyedTable((copy) => copy.resourceTable.processFieldNames, "process field");
const reasons = keyedTable((copy) => copy.performanceOverlay.itemReasons, "overlay item reason");
const entryLines = (table: Record<string, Record<string, string>>) => Object.keys(table).map((key) =>
  `    .{ .key = ${zigString(key)}, .labels = .{ ${languages.map((language) => zigString(table[key][language])).join(", ")} } },`);
const zig = [
  "// Generated by src/UI/Frontend/scripts/generateOverlayMetricLabels.ts from the frontend metric copy. Do not edit.",
  `pub const languages = [_][]const u8{ ${languages.map(zigString).join(", ")} };`,
  "pub const Entry = struct { key: []const u8, labels: [languages.len][]const u8 };",
  "pub const entries = [_]Entry{",
  ...entryLines(labels),
  "};",
  "/// A software item other than the four old target lines: \"{name}\" is the process field name, else the metric name, else the id (performanceOverlay.itemSoftware).",
  `pub const software_template = [languages.len][]const u8{ ${languages.map((language) => zigString(softwareTemplate[language])).join(", ")} };`,
  "/// Process field names by software item id (resourceTable.processFieldNames).",
  "pub const process_fields = [_]Entry{",
  ...entryLines(processFields),
  "};",
  "/// Why an item has no value, by the backend's reason code (performanceOverlay.itemReasons).",
  "pub const reasons = [_]Entry{",
  ...entryLines(reasons),
  "};",
  ""
].join("\n");
// The Zig table is compiled into the resident overlay, the only overlay producer.
const outputs = [
  [fileURLToPath(new URL("../../Desktop/src/text/generated/overlay_metric_labels.zig", import.meta.url)), zig]
];
for (const [destination, output] of outputs) {
  if (process.argv.includes("--check")) {
    const existing = await readFile(destination, "utf8").catch(() => null);
    if (existing !== output)
      throw new Error(`${destination} differs from the frontend copy. Regenerate the overlay metric labels.`);
  } else {
    await writeFile(destination, output, "utf8");
  }
}
