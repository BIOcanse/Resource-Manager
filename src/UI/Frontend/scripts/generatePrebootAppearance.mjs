// 按 src/Shared/Appearance/ui-styles.json 生成 index.html 里预启动的底色表，规则见 docs/ui_styles.md。
// --check 只比对不写入。
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const catalogPath = fileURLToPath(new URL("../../../Shared/Appearance/ui-styles.json", import.meta.url));
const indexPath = fileURLToPath(new URL("../index.html", import.meta.url));
const begin = "      /* preboot-appearance:begin (generated by scripts/generatePrebootAppearance.mjs) */";
const end = "      /* preboot-appearance:end */";

const catalog = JSON.parse(await readFile(catalogPath, "utf8"));
const rgb = (hex) => {
  const match = /^#([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})$/i.exec(hex);
  if (!match) throw new Error(`Invalid startup background ${hex}`);
  return `rgb(${match.slice(1).map((part) => parseInt(part, 16)).join(", ")})`;
};
const scheme = (hex) => {
  const [r, g, b] = /^#(..)(..)(..)$/.exec(hex).slice(1).map((part) => parseInt(part, 16) / 255);
  return 0.2126 * r + 0.7152 * g + 0.0722 * b < 0.5 ? "dark" : "light";
};
const rule = (indent, selector, hex) => [
  `${indent}${selector} {`,
  `${indent}  color-scheme: ${scheme(hex)};`,
  `${indent}  --preboot-background: ${rgb(hex)};`,
  `${indent}}`
];

const lines = [begin];
const darkLines = [];
for (const style of catalog.styles) {
  const palettes = new Map(style.palettes.map((palette) => [palette.id, palette]));
  for (const palette of style.palettes) {
    const selector = `html[data-ui-style="${style.id}"][data-theme="${palette.id}"]`;
    if (palette.follows) {
      lines.push(...rule("      ", selector, palettes.get(palette.follows.light).startupBackground));
      darkLines.push(...rule("        ", selector, palettes.get(palette.follows.dark).startupBackground));
    } else {
      lines.push(...rule("      ", selector, palette.startupBackground));
    }
  }
}
lines.push("      @media (prefers-color-scheme: dark) {", ...darkLines, "      }", end);

const index = await readFile(indexPath, "utf8");
const newline = index.includes("\r\n") ? "\r\n" : "\n";
const start = index.indexOf(begin);
const stop = index.indexOf(end);
if (start < 0 || stop < start) throw new Error("index.html is missing the preboot-appearance markers.");
const output = index.slice(0, start) + lines.join(newline) + index.slice(stop + end.length);
if (process.argv.includes("--check")) {
  if (output !== index) throw new Error("index.html preboot backgrounds differ from ui-styles.json. Run scripts/generatePrebootAppearance.mjs.");
} else {
  await writeFile(indexPath, output, "utf8");
}
